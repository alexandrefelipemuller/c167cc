#include "c167cc/c167_target.h"
#include <stdio.h>

static void print_line(AsmLine *l, FILE *out) {
    if (l->label && !l->mnemonic) {
        fprintf(out, "%s:", l->label);
        if (l->comment) fprintf(out, "\t\t\t\t; %s", l->comment);
        fprintf(out, "\n");
        return;
    }
    if (!l->mnemonic && !l->label) {
        if (l->comment) fprintf(out, "\t; %s\n", l->comment);
        return;
    }
    fprintf(out, "\t%-8s", l->mnemonic);
    if (l->operands) fprintf(out, " %-20s", l->operands);
    else fprintf(out, "%-21s", "");
    if (l->comment) fprintf(out, "; %s", l->comment);
    fprintf(out, "\n");
}

void c167_print(AsmProgram *prog, FILE *out) {
    fprintf(out, "; Generated by c167cc - do not edit by hand.\n");
    fprintf(out, "; Target: Siemens/Infineon C167CR\n");
    fprintf(out, "; See docs/assembly-syntax.md for the syntax and instruction reference.\n\n");

    if (prog->globals) {
        fprintf(out, "\t.section .bss\n");
        for (AsmGlobal *g = prog->globals; g; g = g->next) {
            if (g->sym->has_abs_addr) {
                fprintf(out, "%s\t\tEQU\t0%lXH\t\t; %s @0x%lX (%s)\n",
                        g->name, g->sym->abs_addr, (g->sym->attrs & ATTR_ROM) ? "@rom" : "@ram",
                        g->sym->abs_addr, type_name(g->sym->type));
            } else {
                fprintf(out, "%s:\t\tDS\t%d\t\t; %s\n", g->name, type_size(g->sym->type), type_name(g->sym->type));
            }
        }
        fprintf(out, "\n");
    }

    fprintf(out, "\t.section .text\n");
    for (AsmFunc *f = prog->funcs; f; f = f->next) {
        if (f->is_global) fprintf(out, "\t.global %s\n", f->name);
    }
    fprintf(out, "\n");

    for (AsmFunc *f = prog->funcs; f; f = f->next) {
        for (AsmLine *l = f->head; l; l = l->next) print_line(l, out);
        fprintf(out, "\n");
    }
}
